import SwiftUI
import WebKit
import AppUI

/// A cross-platform, security-isolated offline WebKit view for rendering HTML content and interactive diagrams.
/// Strictly enforces local-only rendering, prevents external network hops, and automatically injects ink-wash theme CSS tokens.
public struct RichContentWebView: View {
    public let htmlString: String
    public let isScrollEnabled: Bool
    public var onHeightCalculated: ((CGFloat) -> Void)?

    @Environment(\.colorScheme) private var colorScheme
    @State private var internalHeight: CGFloat = 200

    public init(
        htmlString: String,
        isScrollEnabled: Bool = false,
        onHeightCalculated: ((CGFloat) -> Void)? = nil
    ) {
        self.htmlString = htmlString
        self.isScrollEnabled = isScrollEnabled
        self.onHeightCalculated = onHeightCalculated
    }

    public var body: some View {
        Group {
            if isScrollEnabled {
                // Fullscreen expanded mode: fill entire available viewport, native scrolling without height constraints
                RepresentedWebView(
                    htmlString: prepareHTML(htmlString, colorScheme: colorScheme, interactive: true),
                    isScrollEnabled: true,
                    onHeightCalculated: nil
                )
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                // Card preview mode: constrained to measured content height
                RepresentedWebView(
                    htmlString: prepareHTML(htmlString, colorScheme: colorScheme, interactive: false),
                    isScrollEnabled: false,
                    onHeightCalculated: { height in
                        internalHeight = max(80, height)
                        onHeightCalculated?(internalHeight)
                    }
                )
                .frame(height: internalHeight)
            }
        }
    }

    /// Prepares HTML for rendering, ensuring CSP security, responsive viewport, and ink-wash tokens.
    private func prepareHTML(_ raw: String, colorScheme: ColorScheme, interactive: Bool) -> String {
        let isDark = colorScheme == .dark
        let bgColor = isDark ? "#221B12" : "#F7F1E7"
        let textColor = isDark ? "#EFE6D5" : "#211B12"
        let secondaryColor = isDark ? "#B0A491" : "#5B5245"
        let hairlineColor = isDark ? "rgba(255,255,255,0.09)" : "rgba(33,20,0,0.09)"
        let accentColor = isDark ? "#D06450" : "#9F3C2E"

        let hasFullHtml = raw.lowercased().contains("<html") || raw.lowercased().contains("<!doctype")
        if hasFullHtml {
            // Already a complete self-contained document (such as generated by MermaidDiagramView)
            return raw
        }

        // Snippet mode: wrap in standard ink-wash styling container with strict CSP
        let safePadding = interactive
            ? "padding: 20px 16px 80px 16px;"
            : "padding: 10px 8px;"

        let cspMeta = """
        <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data: blob:; connect-src 'none';">
        """

        return """
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset="utf-8">
            \(cspMeta)
            <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=3.0, user-scalable=\(interactive ? "yes" : "no")">
            <style>
                :root {
                    --bg-surface: \(bgColor);
                    --text-primary: \(textColor);
                    --text-secondary: \(secondaryColor);
                    --hairline: \(hairlineColor);
                    --accent: \(accentColor);
                }
                * { box-sizing: border-box; max-width: 100%; }
                html, body {
                    width: 100%;
                    margin: 0;
                    background-color: var(--bg-surface);
                    color: var(--text-primary);
                    font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
                    -webkit-text-size-adjust: 100%;
                }
                body {
                    \(safePadding)
                    font-size: 14px;
                    line-height: 1.5;
                    word-break: break-word;
                    overflow-x: hidden;
                }
                table {
                    width: 100%;
                    border-collapse: collapse;
                    margin: 6px 0;
                    font-size: 13px;
                }
                th, td {
                    padding: 6px 10px;
                    border: 1px solid var(--hairline);
                    text-align: left;
                }
                th {
                    background-color: rgba(0,0,0,0.04);
                    font-weight: 600;
                }
                img {
                    max-width: 100%;
                    height: auto;
                    border-radius: 6px;
                }
                pre, code {
                    font-family: ui-monospace, Menlo, Monaco, "Cascadia Mono", monospace;
                    background: rgba(0,0,0,0.05);
                    border-radius: 4px;
                    font-size: 12px;
                }
            </style>
        </head>
        <body>
            \(raw)
        </body>
        </html>
        """
    }
}

// MARK: - Cross-Platform WKWebView Implementation

#if os(iOS)
private struct RepresentedWebView: UIViewRepresentable {
    let htmlString: String
    let isScrollEnabled: Bool
    let onHeightCalculated: ((CGFloat) -> Void)?

    func makeUIView(context: Context) -> WKWebView {
        let config = WKWebViewConfiguration()
        config.defaultWebpagePreferences.allowsContentJavaScript = true
        // Allow disk caching so static engines load in 0ms on subsequent views
        config.websiteDataStore = .default()

        let webView = WKWebView(frame: .zero, configuration: config)
        webView.isOpaque = false
        webView.backgroundColor = .clear
        webView.scrollView.backgroundColor = .clear
        webView.scrollView.isScrollEnabled = isScrollEnabled
        webView.scrollView.alwaysBounceVertical = isScrollEnabled
        webView.scrollView.contentInsetAdjustmentBehavior = .automatic
        webView.navigationDelegate = context.coordinator
        return webView
    }

    func updateUIView(_ webView: WKWebView, context: Context) {
        webView.scrollView.isScrollEnabled = isScrollEnabled
        webView.scrollView.alwaysBounceVertical = isScrollEnabled
        context.coordinator.onHeightCalculated = onHeightCalculated

        if context.coordinator.currentHTML != htmlString {
            context.coordinator.currentHTML = htmlString
            webView.loadHTMLString(htmlString, baseURL: nil)
        }
    }

    func makeCoordinator() -> Coordinator {
        Coordinator(onHeightCalculated: onHeightCalculated)
    }

    class Coordinator: NSObject, WKNavigationDelegate {
        var currentHTML: String = ""
        var onHeightCalculated: ((CGFloat) -> Void)?

        init(onHeightCalculated: ((CGFloat) -> Void)?) {
            self.onHeightCalculated = onHeightCalculated
        }

        func webView(_ webView: WKWebView, didFinish navigation: WKNavigation!) {
            guard let onHeightCalculated = onHeightCalculated else { return }
            webView.evaluateJavaScript("Math.max(document.body.scrollHeight, document.documentElement.scrollHeight)") { result, _ in
                if let height = result as? CGFloat, height > 0 {
                    DispatchQueue.main.async {
                        onHeightCalculated(height)
                    }
                }
            }
        }

        func webView(_ webView: WKWebView, decidePolicyFor navigationAction: WKNavigationAction, decisionHandler: @escaping (WKNavigationActionPolicy) -> Void) {
            if navigationAction.navigationType == .linkActivated {
                decisionHandler(.cancel)
            } else {
                decisionHandler(.allow)
            }
        }
    }
}
